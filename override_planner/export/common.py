"""Shared export logic: turns a timeline into a list of abstract motion steps."""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Optional

from ..model.actions import Action
from ..model.geometry import dist, norm_heading
from ..model.path import FIELD_SIZE, Route
from ..model.profile import RobotConfig, Timeline, build_timeline


@dataclass
class ExportOptions:
    origin: str = "center"          # "center" | "bottom_left"
    timeout_scale: float = 1.5      # timeout = estimated time * scale + pad
    timeout_pad_ms: int = 300
    function_name: str = "autonRoute"
    include_comments: bool = True


@dataclass
class Step:
    kind: str                       # set_pose | turn_point | turn_heading | drive | curve | action | comment
    x: float = 0.0
    y: float = 0.0
    h: float = 0.0
    reverse: bool = False
    speed: float = 100.0
    timeout_ms: int = 1000
    distance: float = 0.0
    action: Optional[Action] = None
    text: str = ""
    wp: int = 0


def to_out(x: float, y: float, opts: ExportOptions) -> tuple[float, float]:
    if opts.origin == "center":
        c = FIELD_SIZE / 2
        return x - c, y - c
    return x, y


def fmt(v: float, nd: int = 2) -> str:
    s = f"{v:.{nd}f}"
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def timeout(seconds: float, opts: ExportOptions) -> int:
    ms = seconds * 1000 * opts.timeout_scale + opts.timeout_pad_ms
    return int(math.ceil(ms / 50.0) * 50)


def build_steps(route: Route, robot: RobotConfig, opts: ExportOptions, tl: Optional[Timeline] = None) -> list[Step]:
    tl = tl or build_timeline(route, robot)
    steps: list[Step] = []
    if not route.waypoints:
        return steps
    w0 = route.waypoints[0]
    sx, sy = to_out(w0.x, w0.y, opts)
    steps.append(Step("set_pose", sx, sy, w0.heading or 0.0, wp=0))
    last_wp = 0
    for ph in tl.phases:
        if ph.wp != last_wp and opts.include_comments:
            wp = route.waypoints[ph.wp]
            ox, oy = to_out(wp.x, wp.y, opts)
            extra = " (reverse)" if wp.reverse else ""
            extra += " (curve)" if wp.curve else ""
            steps.append(Step("comment", text=f"Waypoint {ph.wp}: ({fmt(ox)}, {fmt(oy)}){extra}", wp=ph.wp))
        last_wp = ph.wp
        to = timeout(ph.duration, opts)
        if ph.kind == "turn":
            if ph.face_point is not None:
                px, py = to_out(ph.face_point[0], ph.face_point[1], opts)
                steps.append(Step("turn_point", px, py, norm_heading(ph.h1), reverse=route.waypoints[ph.wp].reverse,
                                  timeout_ms=to, wp=ph.wp))
            else:
                steps.append(Step("turn_heading", h=norm_heading(ph.h1), timeout_ms=to, wp=ph.wp))
        elif ph.kind == "drive":
            ex, ey = to_out(ph.end[0], ph.end[1], opts)
            kind = "curve" if ph.curve else "drive"
            steps.append(Step(kind, ex, ey, norm_heading(ph.h1), reverse=ph.reverse, speed=ph.speed,
                              timeout_ms=to, distance=ph.length if ph.curve else dist(ph.pts[0], ph.pts[-1]),
                              wp=ph.wp))
        elif ph.kind == "action" and ph.action is not None:
            steps.append(Step("action", action=ph.action, timeout_ms=int(round(ph.action.duration * 1000)), wp=ph.wp))
    return steps


def header(route: Route, robot: RobotConfig, opts: ExportOptions, tl: Timeline, flavor: str) -> list[str]:
    origin = "field center" if opts.origin == "center" else "bottom-left corner (audience view)"
    lines = [
        f"// {flavor} auton generated by Override Auton Planner",
        f"// Route: {route.name}   estimated time: {tl.total:.2f} s",
        f"// Units: inches. Origin: {origin}. +Y toward far wall, heading 0 = far wall, clockwise positive.",
    ]
    snippets = sorted({s for w in route.waypoints for a in w.actions for s in [a.snippet()] if s})
    if snippets:
        lines.append("// Implement these mechanism helpers for your robot: " + " ".join(snippets))
    return lines


def speed127(pct: float) -> int:
    return int(round(127 * max(0.0, min(100.0, pct)) / 100.0))
